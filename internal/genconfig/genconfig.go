// Package genconfig writes a starting config file for a DVR: its channels with default names and the detected
// model, and every other option commented out with its default.
package genconfig

import (
	"fmt"
	"io"
	"strconv"
	"strings"
)

// Input is what the config is generated from.
type Input struct {
	Host string
	Port int
	User string
	// PasswordFile is written as dvr.password_file; the password itself never is.
	PasswordFile string
	Channels     int
	Model        string // detected model of every channel
	TypeDesc     string // e.g. "DVR 500 series, 4 channels (type 504)"
}

// quote is a TOML basic string.
func quote(s string) string { return strconv.Quote(s) }

// Write writes the config.
func Write(w io.Writer, in Input) error {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	p("# DVR Squirrel configuration, generated by `dvr-squirrel generate-config`.\n")
	if in.TypeDesc != "" {
		p("# DVR: %s\n", in.TypeDesc)
	}
	p("# Name the cameras below: NVRs show the name and the model. Precedence: flags, environment, this file.\n\n")
	p("[dvr]\nhost = %s\n", quote(in.Host))
	if in.Port != 0 && in.Port != 8000 {
		p("port = %d\n", in.Port)
	} else {
		p("# port = 8000\n")
	}
	p("user = %s\n", quote(in.User))
	p("# A file holding only the password (or set DVR_PASSWORD or DVR_PASSWORD_FILE).\n")
	p("password_file = %s\n", quote(in.PasswordFile))
	p("# reconnect_seconds = 5\n# reconnect_max_seconds = 10\n# web_port = 80\n")
	for i := 1; i <= in.Channels; i++ {
		p("\n[[channel]]\nindex = %d\nname = %s\nmodel = %s\n", i, quote(fmt.Sprintf("CH%d", i)), quote(in.Model))
		p("# listen_ip = \"\"                # its own address, as NVRs tell cameras apart by IP address\n")
		p("# enabled = true\n")
	}
	p("%s", rest)
	_, err := io.WriteString(w, b.String())
	return err
}

// rest is every other option with its default, commented out.
const rest = `
# [web]
# enabled = true                  # status page (public) and DVR settings (DVR login, kept in memory only)
# listen = ":8090"
#
# [discovery]
# enabled = true                  # WS-Discovery responder on UDP 3702
# interface = ""                  # multicast interface; empty: the system default
#
# [snapshot]
# enabled = true                  # decode snapshots with ffmpeg; otherwise a placeholder picture
# ffmpeg = "embedded"             # the embedded one, else "ffmpeg" from PATH; or a name or a path
# cache_seconds = 5
#
# [defaults]
# Inherited by every [[channel]].
# audio = false
# listen_ip = ""
# rtsp_port = 554                 # on a shared address: 8550+n for channel n
# onvif_port = 80                 # on a shared address: 8080+n for channel n
# rtsp_path = "/stream"
# user = ""                       # ONVIF and RTSP login; default: the DVR login
# password_file = ""
# firmware = "1.0"
# filler_image = ""               # PNG or JPEG shown while a channel has no video
# filler_text = true
`
